import { Link, useSearchParams } from "react-router-dom";
import { api } from "../api";
import { StatusBadge, UrgentBadge } from "../components/Badge";
import { DataState } from "../components/StateViews";
import { fmtTime } from "../format";
import { useApi } from "../hooks";

const TABS = ["PENDING", "CLARIFICATION_REQUESTED", "APPROVED", "EXECUTED", "EXECUTION_FAILED", "REJECTED", "ALL"];

export function ReviewsPage() {
  const [params, setParams] = useSearchParams();
  const status = params.get("status") ?? "PENDING";
  const state = useApi(() => api.reviews(status === "ALL" ? undefined : status), [status]);

  return (
    <>
      <div className="page-head">
        <h1>Nurse review queue</h1>
        <button type="button" className="btn btn-small" onClick={state.reload} disabled={state.loading}>
          {state.loading ? "Refreshing…" : "Refresh"}
        </button>
      </div>
      <p className="muted">
        Every item is a proposal generated by the workflow. It requires nurse review; only a decision by an authorized reviewer can change
        the synthetic queue.
      </p>
      <div className="tabs" role="group" aria-label="Filter by review status">
        {TABS.map((t) => (
          <button
            key={t}
            type="button"
            className={`tab ${t === status ? "active" : ""}`}
            aria-pressed={t === status}
            onClick={() => setParams(t === "PENDING" ? {} : { status: t })}
          >
            {t.replace(/_/g, " ")}
          </button>
        ))}
      </div>
      <DataState
        state={state}
        label="reviews"
        isEmpty={(d) => d.length === 0}
        empty={`No reviews with status ${status.replace(/_/g, " ")}.`}
      >
        {(rows) => {
          // Backend already orders urgent first; keep that guarantee client-side too.
          const sorted = [...rows].sort((a, b) => Number(b.urgent_flag) - Number(a.urgent_flag));
          return (
            <ul className="plain-list review-list">
              {sorted.map((r) => (
                <li key={r.id} className={`card review-item ${r.urgent_flag ? "review-urgent" : ""}`}>
                  <div className="review-item-head">
                    {r.urgent_flag ? <UrgentBadge /> : null} <StatusBadge status={r.status} />{" "}
                    <Link to={`/reviews/${r.id}`} className="mono">
                      {r.id}
                    </Link>
                  </div>
                  <div>
                    <strong>
                      {r.given_name} {r.family_name}
                    </strong>{" "}
                    <span className="mono muted small">{r.patient_id}</span> — {r.chief_complaint}
                  </div>
                  <div className="small">
                    Proposal: {r.proposed_priority ? <strong>{r.proposed_priority}</strong> : <em>no priority proposed</em>} · evaluation{" "}
                    <StatusBadge status={r.evaluation_status} />
                    {r.approved_priority ? (
                      <>
                        {" "}
                        · approved priority <strong>{r.approved_priority}</strong>
                      </>
                    ) : null}
                  </div>
                  <div className="muted small">
                    Requested {fmtTime(r.requested_at)}
                    {r.decided_by ? ` · Decision by ${r.decided_by} (${r.decision?.replace(/_/g, " ")}) ${fmtTime(r.decided_at)}` : " · Requires nurse review"}
                  </div>
                  <div>
                    <Link to={`/reviews/${r.id}`}>Open review →</Link>
                  </div>
                </li>
              ))}
            </ul>
          );
        }}
      </DataState>
    </>
  );
}
